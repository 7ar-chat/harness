// localHarness opens a harness on the durable store in dir.
func localHarness(t *testing.T, dir string, model *llmtest.Model) (*harness.Harness, context.Context, func()) {
	t.Helper()
	slog.SetDefault(slog.New(slog.NewTextHandler(io.Discard, nil)))
	t.Setenv("LLM_PROVIDER", "openai")
	t.Setenv("LLM_MODELS", "gpt-test")
	t.Setenv("RUNTIME_SHUTDOWN_GRACE_SECONDS", "1")
	cfg, err := config.Load()
	if err != nil {
		t.Fatal(err)
	}
	st, err := harness.OpenLocalStore(dir)
	if err != nil {
		t.Fatal(err)
	}
	h, err := harness.New(harness.Options{Config: cfg, Store: st, Models: llmtest.Factory{M: model}, Backend: sandboxtest.NewBackend()})
	if err != nil {
		t.Fatal(err)
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	done := make(chan struct{})
	go func() { _ = h.Run(ctx); close(done) }()
	return h, ctx, func() {
		cancel()
		<-done
		if err := st.Close(); err != nil {
			t.Fatal(err)
		}
	}
}

func drain(h *harness.Harness, ctx context.Context, runID string) (types []string) {
	for ev := range h.Events(ctx, runID, 0) {
		types = append(types, ev.Type)
	}
	return types
}

func TestLocalStoreResumesAConversationAfterARestart(t *testing.T) {
	// Arrange: the first process answers one message and exits.
	dir := t.TempDir()
	answer := func(c llmtest.Call) llmtest.Turn { return llmtest.Turn{Chunks: llmtest.Text("reply")} }
	h1, ctx1, stop1 := localHarness(t, dir, llmtest.NewFunc(answer))
	th, err := h1.NewThread(ctx1, "alice", "")
	if err != nil {
		t.Fatal(err)
	}
	run1, err := h1.Send(ctx1, "alice", th.ID, "my favourite colour is teal", harness.RunOptions{Model: "gpt-test"})
	if err != nil {
		t.Fatal(err)
	}
	firstEvents := drain(h1, ctx1, run1.ID)
	waitStatus(t, h1, run1.ID, store.StatusCompleted)
	stop1()

	// Act: a new process on the same directory sends a second message.
	model2 := llmtest.NewFunc(answer)
	h2, ctx2, stop2 := localHarness(t, dir, model2)
	defer stop2()
	run2, err := h2.Send(ctx2, "alice", th.ID, "what is my favourite colour?", harness.RunOptions{Model: "gpt-test"})
	if err != nil {
		t.Fatal(err)
	}
	drain(h2, ctx2, run2.ID)
	waitStatus(t, h2, run2.ID, store.StatusCompleted)

	// Assert: thread, history and the old run's events are there.
	got, err := h2.Store.GetThread(ctx2, "alice", th.ID)
	if err != nil || got.Title != "reply" /* generated by the title hook */ {
		t.Fatalf("thread %+v err %v", got, err)
	}
	msgs, _ := h2.Store.ListMessages(ctx2, th.ID)
	var contents []string
	for _, m := range msgs {
		if m.Role == store.RoleUser || m.Role == store.RoleAssistant {
			contents = append(contents, m.Content)
		}
	}
	if strings.Join(contents, "|") != "my favourite colour is teal|reply|what is my favourite colour?|reply" {
		t.Fatalf("history %q", contents)
	}
	seen := false
	for _, c := range model2.Calls() {
		var sawFirstTurn bool
		for _, m := range c.Messages {
			if strings.Contains(m.Content, "my favourite colour is teal") {
				sawFirstTurn = true
			}
		}
		if sawFirstTurn && strings.Contains(c.Messages[len(c.Messages)-1].Content, "what is my favourite colour?") {
			seen = true
		}
	}
	if !seen {
		t.Fatalf("the model call of the second turn did not see the first turn (%d calls)", len(model2.Calls()))
	}
	replayed := drain(h2, ctx2, run1.ID)
	if len(replayed) == 0 || len(replayed) != len(firstEvents) || replayed[len(replayed)-1] != agui.RunFinished {
		t.Fatalf("replay of the old run: %v, was %v", replayed, firstEvents)
	}
}

func TestLocalStoreMarksARunInterruptedWhenTheProcessDied(t *testing.T) {
	// Arrange: the model blocks, then the process "dies" with the run in flight.
	dir := t.TempDir()
	block := llmtest.NewFunc(func(llmtest.Call) llmtest.Turn { return llmtest.Turn{Chunks: llmtest.Text("partial"), Block: true} })
	h1, ctx1, stop1 := localHarness(t, dir, block)
	th, _ := h1.NewThread(ctx1, "alice", "t")
	run, err := h1.Send(ctx1, "alice", th.ID, "long task", harness.RunOptions{Model: "gpt-test"})
	if err != nil {
		t.Fatal(err)
	}
	waitStatus(t, h1, run.ID, store.StatusRunning)
	// Snapshot the on-disk state as kill -9 leaves it (no shutdown, no Close).
	killed := t.TempDir()
	copyJournal(t, dir, killed)
	stop1()

	// Act
	h2, ctx2, stop2 := localHarness(t, killed, llmtest.NewFunc(func(llmtest.Call) llmtest.Turn { return llmtest.Turn{Chunks: llmtest.Text("ok")} }))
	defer stop2()

	// Assert
	r, err := h2.Store.GetRun(ctx2, run.ID)
	if err != nil || r.Status != store.StatusInterrupted {
		t.Fatalf("run %+v err %v", r, err)
	}
	types := drain(h2, ctx2, run.ID)
	if len(types) == 0 || types[len(types)-1] != agui.RunError {
		t.Fatalf("events %v", types)
	}
	// The thread is usable again.
	run2, err := h2.Send(ctx2, "alice", th.ID, "try again", harness.RunOptions{Model: "gpt-test"})
	if err != nil {
		t.Fatal(err)
	}
	drain(h2, ctx2, run2.ID)
}

func waitStatus(t *testing.T, h *harness.Harness, runID, status string) {
	t.Helper()
	deadline := time.Now().Add(15 * time.Second)
	for time.Now().Before(deadline) {
		if r, err := h.Store.GetRun(context.Background(), runID); err == nil && r.Status == status {
			return
		}
		time.Sleep(10 * time.Millisecond)
	}
	t.Fatalf("run %s never reached %s", runID, status)
}
